"""Write the annotated disassembly of the 720 Degrees main program: re/main_t11.lst

Includes every instruction found by codedb.py (fixed ROM and each code bank), labels for
function entries and branch targets, cross references, hardware register names and the
names from re/symbols.txt.
"""
import os, sys, collections
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import codedb, t11dis

ROOT = os.path.join(HERE, '..')

HW = {
    0x1000: 'PAL_MO', 0x1080: 'PAL_ALPHA', 0x1100: 'PAL_PF',
    0x1400: 'BANK_A', 0x1402: 'BANK_B', 0x1480: 'ADC_START',
    0x1580: 'ACK_SNDCMD_IRQ', 0x15A0: 'SOUND_RESET', 0x15C0: 'ACK_32V_IRQ', 0x15E0: 'ACK_VBLANK_IRQ',
    0x1600: 'IRQ_ENABLE', 0x1680: 'SOUND_CMD', 0x1700: 'XSCROLL', 0x1780: 'YSCROLL',
    0x1800: 'IN0_WATCHDOG', 0x1C00: 'SOUND_RESPONSE',
    0x2000: 'VRAM', 0x3800: 'MO_RAM',
    0x8000: 'SLAPSTIC_RESET', 0x8030: 'SLAPSTIC_BANK0', 0x8034: 'SLAPSTIC_BANK1',
    0x8038: 'SLAPSTIC_BANK2', 0x803C: 'SLAPSTIC_BANK3',
}


def load_symbols():
    syms = {}
    f = os.path.join(ROOT, 're', 'symbols.txt')
    if os.path.exists(f):
        for line in open(f):
            line = line.split('#')[0].strip()
            if not line:
                continue
            p = line.split()
            if len(p) >= 2:
                if ':' in p[0]:
                    s, a = p[0].split(':')
                    syms[(s.upper(), int(a, 16))] = p[1]
                else:
                    syms[('DATA', int(p[0], 16))] = p[1]
    return syms


def main():
    db = codedb.build()
    syms = load_symbols()
    labels = {}
    xrefs = collections.defaultdict(list)
    for (s, a) in db.seen:
        ins = db.insns[(s, a)]
        if ins.target is not None:
            ts = codedb.target_seg(s, ins.target)
            if ts:
                xrefs[(ts, ins.target)].append((s, a, ins.mn))
    for k, why in db.entries.items():
        labels[k] = 'sub' if why in ('call', 'csvbody') else why
    for k in xrefs:
        labels.setdefault(k, 'loc')

    def name(seg, a):
        if (seg, a) in syms:
            return syms[(seg, a)]
        if ('DATA', a) in syms and a < 0x4000:
            return syms[('DATA', a)]
        kind = labels.get((seg, a))
        if kind in ('sub', 'loc'):
            return '%s_%s_%04X' % (kind, seg, a)
        if kind:
            return '%s_%04X' % (kind, a)
        return '%s_%04X' % (seg, a)

    def sym_for(seg):
        def f(v):
            if (seg, v) in labels or (seg, v) in syms:
                return name(seg, v)
            if v >= 0x8000 and ('F', v) in labels:
                return name('F', v)
            if v in HW:
                return HW[v]
            if ('DATA', v) in syms:
                return syms[('DATA', v)]
            return '0x%04X' % v
        return f

    out = []
    out.append('; 720 Degrees (Atari Games 1986, rev 4) - main program, DEC T-11')
    out.append('; Generated by tools/listing.py from the code database (coverage + static analysis).')
    out.append('; Segments: F = fixed ROM 0x8000-0xFFFF; An = ROM bank n mapped at 0x4000; Bn = ROM bank n at 0x6000.')
    out.append('')
    segs = sorted(set(s for s, a in db.seen), key=lambda s: (s != 'F', s))
    for s in segs:
        addrs = sorted(a for (ss, a) in db.seen if ss == s)
        out.append('')
        out.append(';' + '=' * 78)
        out.append('; segment %s' % s)
        out.append(';' + '=' * 78)
        prev_end = None
        for a in addrs:
            ins = db.insns[(s, a)]
            if prev_end is not None and a != prev_end:
                out.append('')
            k = (s, a)
            if k in labels or k in syms:
                if labels.get(k) in ('sub',) or k in db.entries:
                    out.append('')
                    out.append('; ' + '-' * 60)
                refs = xrefs.get(k, [])
                if refs:
                    out.append('; xref: ' + ', '.join('%s:%04X %s' % r for r in refs[:8]) + (' ...' if len(refs) > 8 else ''))
                out.append('%s:' % name(s, a))
            cov = '' if (s, a) in db.covered else ' ?'
            words = ' '.join('%04X' % w for w in ins.words)
            out.append('    %04X  %-15s %s%s' % (a, words, ins.text(sym_for(s)), cov))
            prev_end = (a + ins.size) & 0xffff
    open(os.path.join(ROOT, 're', 'main_t11.lst'), 'w').write('\n'.join(out) + '\n')
    print('wrote re/main_t11.lst: %d lines' % len(out))


if __name__ == '__main__':
    main()
