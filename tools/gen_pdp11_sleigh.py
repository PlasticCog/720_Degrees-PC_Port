"""Generate a Ghidra processor module for the DEC T-11 (PDP-11 subset) -> re/ghidra/PDP11

The module gives Ghidra a disassembler + decompiler for the 720 Degrees main program.
Install by copying re/ghidra/PDP11 to <ghidra>/Ghidra/Processors/PDP11 (see re/ghidra/README.md).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 're', 'ghidra', 'PDP11')
LANG = os.path.join(OUT, 'data', 'languages')

S = []
w = S.append

w('''# DEC T-11 / PDP-11 (no EIS/FPU) SLEIGH specification, generated by tools/gen_pdp11_sleigh.py
define endian=little;
define alignment=2;

define space ram type=ram_space size=2 default;
define space register type=register_space size=2;

define register offset=0x00 size=2 [ R0 R1 R2 R3 R4 R5 SP PC ];
define register offset=0x00 size=1 [ R0l R0h R1l R1h R2l R2h R3l R3h R4l R4h R5l R5h SPl SPh PCl PCh ];
define register offset=0x20 size=1 [ NF ZF VF CF TF IPL ];
define register offset=0x30 size=2 [ PSW ];
define register offset=0x40 size=4 contextreg;

define context contextreg
  guard   = (0,0)
  c_dmode = (1,3)
  c_dreg  = (4,6)
  c_dregb = (4,6)
  c_dregx = (4,6)
  c_draw  = (4,6)
;

define token instr(16)
  op4    = (12,15)
  op7    = (9,15)
  op8    = (8,15)
  op10   = (6,15)
  op13   = (3,15)
  op16   = (0,15)
  smode  = (9,11)
  sreg   = (6,8)
  sregb  = (6,8)
  sregx  = (6,8)
  sregr  = (6,8)
  dmode  = (3,5)
  dreg   = (0,2)
  dregr  = (0,2)
  boff   = (0,7) signed
  sobo   = (0,5)
  trapc  = (0,7)
  ccn    = (3,3)
  ccz    = (2,2)
  ccv    = (1,1)
  ccc    = (0,0)
  ccall  = (0,3)
;
define token ext(16)
  x  = (0,15)
  xs = (0,15) signed
;

attach variables [ sreg sregx dreg c_dreg ] [ R0 R1 R2 R3 R4 R5 SP PC ];
attach variables [ sregb c_dregb ] [ R0l R1l R2l R3l R4l R5l SPl PCl ];

define pcodeop halt;
define pcodeop wait;
define pcodeop reset;
define pcodeop trap_emt;
define pcodeop trap_trap;
define pcodeop trap_bpt;
define pcodeop trap_iot;
define pcodeop mfpt;

macro packpsw() { PSW = zext(IPL << 5) | zext(TF << 4) | zext(NF << 3) | zext(ZF << 2) | zext(VF << 1) | zext(CF); }
macro unpackpsw(v) { CF = (v & 1) != 0; VF = (v & 2) != 0; ZF = (v & 4) != 0; NF = (v & 8) != 0; TF = (v & 0x10) != 0; IPL = (v >> 5) & 7; }
macro nzw(v) { NF = v s< 0; ZF = v == 0; }
macro nzb(v) { NF = v s< 0; ZF = v == 0; }
macro push(v) { SP = SP - 2; *:2 SP = v; }
macro pop(v) { v = *:2 SP; SP = SP + 2; }

# guard prefix: copy destination fields into context so the destination operand
# can consume its extension word after the source operand's extension word
:^instruction is guard=0 & dmode & dregr & instruction [ guard=1; c_dmode=dmode; c_draw=dregr; ] {}

with : guard=1 {
''')

# ------------------------------------------------------------------ operand subtables
# Source operands: matched in the instruction word, consume the first extension word.
w('''
SrcW: sreg            is smode=0 & sreg                 { export sreg; }
SrcW: "("^sreg^")"    is smode=1 & sreg                 { export *:2 sreg; }
SrcW: "#"^x           is smode=2 & sregr=7 ; x          { export *[const]:2 x; }
SrcW: "("^sreg^")+"   is smode=2 & sreg                 { local a = sreg; sreg = sreg + 2; export *:2 a; }
SrcW: "@#"^x          is smode=3 & sregr=7 ; x          { export *:2 x; }
SrcW: "@("^sreg^")+"  is smode=3 & sreg                 { local a = sreg; sreg = sreg + 2; local p:2 = *:2 a; export *:2 p; }
SrcW: "-("^sreg^")"   is smode=4 & sreg                 { sreg = sreg - 2; export *:2 sreg; }
SrcW: "@-("^sreg^")"  is smode=5 & sreg                 { sreg = sreg - 2; local p:2 = *:2 sreg; export *:2 p; }
SrcW: addr            is smode=6 & sregr=7 ; xs         [ addr = inst_start + 4 + xs; ] { export *:2 addr; }
SrcW: xs^"("^sreg^")" is smode=6 & sreg ; xs            { local a = sreg + xs; export *:2 a; }
SrcW: "@"^addr        is smode=7 & sregr=7 ; xs         [ addr = inst_start + 4 + xs; ] { local p:2 = *:2 addr:2; export *:2 p; }
SrcW: "@"^xs^"("^sreg^")" is smode=7 & sreg ; xs        { local a = sreg + xs; local p:2 = *:2 a; export *:2 p; }

SrcB: sregb           is smode=0 & sregb                { export sregb; }
SrcB: "("^sreg^")"    is smode=1 & sreg                 { export *:1 sreg; }
SrcB: "#"^x           is smode=2 & sregr=7 ; x          { local v:1 = x:1; export v; }
SrcB: "("^sreg^")+"   is smode=2 & sreg & (sregr=6)     { local a = sreg; sreg = sreg + 2; export *:1 a; }
SrcB: "("^sreg^")+"   is smode=2 & sreg                 { local a = sreg; sreg = sreg + 1; export *:1 a; }
SrcB: "@#"^x          is smode=3 & sregr=7 ; x          { export *:1 x; }
SrcB: "@("^sreg^")+"  is smode=3 & sreg                 { local a = sreg; sreg = sreg + 2; local p:2 = *:2 a; export *:1 p; }
SrcB: "-("^sreg^")"   is smode=4 & sreg & (sregr=6)     { sreg = sreg - 2; export *:1 sreg; }
SrcB: "-("^sreg^")"   is smode=4 & sreg                 { sreg = sreg - 1; export *:1 sreg; }
SrcB: "@-("^sreg^")"  is smode=5 & sreg                 { sreg = sreg - 2; local p:2 = *:2 sreg; export *:1 p; }
SrcB: addr            is smode=6 & sregr=7 ; xs         [ addr = inst_start + 4 + xs; ] { export *:1 addr; }
SrcB: xs^"("^sreg^")" is smode=6 & sreg ; xs            { local a = sreg + xs; export *:1 a; }
SrcB: "@"^addr        is smode=7 & sregr=7 ; xs         [ addr = inst_start + 4 + xs; ] { local p:2 = *:2 addr:2; export *:1 p; }
SrcB: "@"^xs^"("^sreg^")" is smode=7 & sreg ; xs        { local a = sreg + xs; local p:2 = *:2 a; export *:1 p; }
''')
# Destination operands: matched on context (c_dmode/c_dreg), consume the next extension word.
w('''
DstW: c_dreg          is c_dmode=0 & c_dreg             { export c_dreg; }
DstW: "("^c_dreg^")"  is c_dmode=1 & c_dreg             { export *:2 c_dreg; }
DstW: "#"^x           is c_dmode=2 & c_dregx=7 ; x      { export *[const]:2 x; }
DstW: "("^c_dreg^")+" is c_dmode=2 & c_dreg             { local a = c_dreg; c_dreg = c_dreg + 2; export *:2 a; }
DstW: "@#"^x          is c_dmode=3 & c_dregx=7 ; x      { export *:2 x; }
DstW: "@("^c_dreg^")+" is c_dmode=3 & c_dreg            { local a = c_dreg; c_dreg = c_dreg + 2; local p:2 = *:2 a; export *:2 p; }
DstW: "-("^c_dreg^")" is c_dmode=4 & c_dreg             { c_dreg = c_dreg - 2; export *:2 c_dreg; }
DstW: "@-("^c_dreg^")" is c_dmode=5 & c_dreg            { c_dreg = c_dreg - 2; local p:2 = *:2 c_dreg; export *:2 p; }
DstW: addr            is c_dmode=6 & c_dregx=7 ; xs     [ addr = inst_next + xs; ] { export *:2 addr; }
DstW: xs^"("^c_dreg^")" is c_dmode=6 & c_dreg ; xs      { local a = c_dreg + xs; export *:2 a; }
DstW: "@"^addr        is c_dmode=7 & c_dregx=7 ; xs     [ addr = inst_next + xs; ] { local p:2 = *:2 addr:2; export *:2 p; }
DstW: "@"^xs^"("^c_dreg^")" is c_dmode=7 & c_dreg ; xs  { local a = c_dreg + xs; local p:2 = *:2 a; export *:2 p; }

DstB: c_dregb         is c_dmode=0 & c_dregb            { export c_dregb; }
DstB: "("^c_dreg^")"  is c_dmode=1 & c_dreg             { export *:1 c_dreg; }
DstB: "#"^x           is c_dmode=2 & c_dregx=7 ; x      { export *:1 inst_next; }
DstB: "("^c_dreg^")+" is c_dmode=2 & c_dreg & c_dregx=6 { local a = c_dreg; c_dreg = c_dreg + 2; export *:1 a; }
DstB: "("^c_dreg^")+" is c_dmode=2 & c_dreg             { local a = c_dreg; c_dreg = c_dreg + 1; export *:1 a; }
DstB: "@#"^x          is c_dmode=3 & c_dregx=7 ; x      { export *:1 x; }
DstB: "@("^c_dreg^")+" is c_dmode=3 & c_dreg            { local a = c_dreg; c_dreg = c_dreg + 2; local p:2 = *:2 a; export *:1 p; }
DstB: "-("^c_dreg^")" is c_dmode=4 & c_dreg & c_dregx=6 { c_dreg = c_dreg - 2; export *:1 c_dreg; }
DstB: "-("^c_dreg^")" is c_dmode=4 & c_dreg             { c_dreg = c_dreg - 1; export *:1 c_dreg; }
DstB: "@-("^c_dreg^")" is c_dmode=5 & c_dreg            { c_dreg = c_dreg - 2; local p:2 = *:2 c_dreg; export *:1 p; }
DstB: addr            is c_dmode=6 & c_dregx=7 ; xs     [ addr = inst_next + xs; ] { export *:1 addr; }
DstB: xs^"("^c_dreg^")" is c_dmode=6 & c_dreg ; xs      { local a = c_dreg + xs; export *:1 a; }
DstB: "@"^addr        is c_dmode=7 & c_dregx=7 ; xs     [ addr = inst_next + xs; ] { local p:2 = *:2 addr:2; export *:1 p; }
DstB: "@"^xs^"("^c_dreg^")" is c_dmode=7 & c_dreg ; xs  { local a = c_dreg + xs; local p:2 = *:2 a; export *:1 p; }

# address operands for JMP/JSR (export the effective address itself)
DstA: "("^c_dreg^")"  is c_dmode=1 & c_dreg             { export c_dreg; }
DstA: "("^c_dreg^")+" is c_dmode=2 & c_dreg             { local a = c_dreg; c_dreg = c_dreg + 2; export a; }
DstA: "@#"^x          is c_dmode=3 & c_dregx=7 ; x      { export *[const]:2 x; }
DstA: "@("^c_dreg^")+" is c_dmode=3 & c_dreg            { local a = c_dreg; c_dreg = c_dreg + 2; local p:2 = *:2 a; export p; }
DstA: "-("^c_dreg^")" is c_dmode=4 & c_dreg             { c_dreg = c_dreg - 2; export c_dreg; }
DstA: "@-("^c_dreg^")" is c_dmode=5 & c_dreg            { c_dreg = c_dreg - 2; local p:2 = *:2 c_dreg; export p; }
DstA: addr            is c_dmode=6 & c_dregx=7 ; xs     [ addr = inst_next + xs; ] { export *[const]:2 addr; }
DstA: xs^"("^c_dreg^")" is c_dmode=6 & c_dreg ; xs      { local a = c_dreg + xs; export a; }
DstA: "@"^addr        is c_dmode=7 & c_dregx=7 ; xs     [ addr = inst_next + xs; ] { local p:2 = *:2 addr:2; export p; }
DstA: "@"^xs^"("^c_dreg^")" is c_dmode=7 & c_dreg ; xs  { local a = c_dreg + xs; local p:2 = *:2 a; export p; }

# static jump/call targets
DstJ: "@#"^x          is c_dmode=3 & c_dregx=7 ; x      { export *:2 x; }
DstJ: addr            is c_dmode=6 & c_dregx=7 ; xs     [ addr = inst_next + xs; ] { export *:2 addr; }

Rel: dest is boff [ dest = inst_next + boff * 2; ] { export *:2 dest; }
SobT: dest is sobo [ dest = inst_next - sobo * 2; ] { export *:2 dest; }
''')

# ------------------------------------------------------------------ compiler register-save prologues
# JSR R1,@#F138 / F144 / F152 / F162 (csv): saves registers and calls the body back;
# modelled as an inline prologue so the decompiler sees normal stack frames.
for addr, regs, epi in ((0xF138, ['R2'], 0xF142), (0xF144, ['R3', 'R2'], 0xF150),
                        (0xF152, ['R4', 'R3', 'R2'], 0xF160), (0xF162, ['R5', 'R4', 'R3', 'R2'], 0xF172)):
    body = 'push(R1); '
    for r in regs[::-1]:
        pass
    # actual order: JSR pushes R1; helper pushes R2,(R3..)
    pushes = ''.join('push(%s); ' % r for r in (['R2', 'R3', 'R4', 'R5'][:len(regs)]))
    w(':CSV_SAVE%d is op16=0x085F ; x=0x%04X { push(R1); %spush(0x%04X:2); }' % (len(regs) + 1, addr, pushes, epi))

# ------------------------------------------------------------------ double operand
for name, op, kind in (('MOV', 1, 'mov'), ('CMP', 2, 'cmp'), ('BIT', 3, 'bit'), ('BIC', 4, 'bic'), ('BIS', 5, 'bis'),
                       ('ADD', 6, 'add'), ('SUB', 14, 'sub')):
    sem = {
        'mov': 'local s = SrcW; DstW = s; nzw(s); VF = 0;',
        'cmp': 'local s = SrcW; local d = DstW; local r = s - d; nzw(r); VF = sborrow(s, d); CF = s < d;',
        'bit': 'local s = SrcW; local d = DstW; local r = s & d; nzw(r); VF = 0;',
        'bic': 'local s = SrcW; local r = DstW & ~s; DstW = r; nzw(r); VF = 0;',
        'bis': 'local s = SrcW; local r = DstW | s; DstW = r; nzw(r); VF = 0;',
        'add': 'local s = SrcW; local d = DstW; local r = d + s; CF = carry(d, s); VF = scarry(d, s); DstW = r; nzw(r);',
        'sub': 'local s = SrcW; local d = DstW; local r = d - s; CF = d < s; VF = sborrow(d, s); DstW = r; nzw(r);',
    }[kind]
    w(':%s SrcW,DstW is (op4=%d)... & SrcW ; DstW { %s }' % (name, op, sem))
for name, op, kind in (('MOVB', 9, 'mov'), ('CMPB', 10, 'cmp'), ('BITB', 11, 'bit'), ('BICB', 12, 'bic'), ('BISB', 13, 'bis')):
    sem = {
        'mov': 'local s = SrcB; DstB = s; nzb(s); VF = 0;',
        'cmp': 'local s = SrcB; local d = DstB; local r = s - d; nzb(r); VF = sborrow(s, d); CF = s < d;',
        'bit': 'local s = SrcB; local d = DstB; local r = s & d; nzb(r); VF = 0;',
        'bic': 'local s = SrcB; local r = DstB & ~s; DstB = r; nzb(r); VF = 0;',
        'bis': 'local s = SrcB; local r = DstB | s; DstB = r; nzb(r); VF = 0;',
    }[kind]
    if kind == 'mov':
        # MOVB to a register sign-extends into the full register
        w(':MOVB SrcB,c_dreg is (op4=9 & dmode=0)... & SrcB ; c_dreg { local s = SrcB; c_dreg = sext(s); nzb(s); VF = 0; }')
    w(':%s SrcB,DstB is (op4=%d)... & SrcB ; DstB { %s }' % (name, op, sem))
w(':XOR sregx,DstW is op7=0x3C & sregx ; DstW { local s = sregx; local r = DstW ^ s; DstW = r; nzw(r); VF = 0; }')

# ------------------------------------------------------------------ single operand
SINGLE = [
    ('CLR', 0o0050, 'DstW = 0; NF = 0; ZF = 1; VF = 0; CF = 0;'),
    ('COM', 0o0051, 'local r = ~DstW; DstW = r; nzw(r); VF = 0; CF = 1;'),
    ('INC', 0o0052, 'local d = DstW; VF = d == 0x7fff; local r = d + 1; DstW = r; nzw(r);'),
    ('DEC', 0o0053, 'local d = DstW; VF = d == 0x8000; local r = d - 1; DstW = r; nzw(r);'),
    ('NEG', 0o0054, 'local d = DstW; local r = -d; DstW = r; nzw(r); VF = r == 0x8000; CF = r != 0;'),
    ('ADC', 0o0055, 'local d = DstW; local c:2 = zext(CF); local r = d + c; VF = scarry(d, c); CF = carry(d, c); DstW = r; nzw(r);'),
    ('SBC', 0o0056, 'local d = DstW; local c:2 = zext(CF); local r = d - c; VF = sborrow(d, c); CF = d < c; DstW = r; nzw(r);'),
    ('TST', 0o0057, 'local d = DstW; nzw(d); VF = 0; CF = 0;'),
    ('ROR', 0o0060, 'local d = DstW; local c:2 = zext(CF); local r = (d >> 1) | (c << 15); CF = (d & 1) != 0; DstW = r; nzw(r); VF = NF ^ CF;'),
    ('ROL', 0o0061, 'local d = DstW; local c:2 = zext(CF); local r = (d << 1) | c; CF = d s< 0; DstW = r; nzw(r); VF = NF ^ CF;'),
    ('ASR', 0o0062, 'local d = DstW; local r = d s>> 1; CF = (d & 1) != 0; DstW = r; nzw(r); VF = NF ^ CF;'),
    ('ASL', 0o0063, 'local d = DstW; local r = d << 1; CF = d s< 0; DstW = r; nzw(r); VF = NF ^ CF;'),
    ('SXT', 0o0067, 'local r:2 = zext(NF) * 0xffff; DstW = r; ZF = NF == 0; VF = 0;'),
    ('SWAB', 0o0003, 'local d = DstW; local r = (d >> 8) | (d << 8); DstW = r; local lo:1 = r:1; nzb(lo); VF = 0; CF = 0;'),
]
for name, op, sem in SINGLE:
    w(':%s DstW is op10=0x%03X ; DstW { %s }' % (name, op, sem))
SINGLEB = [
    ('CLRB', 0o1050, 'DstB = 0; NF = 0; ZF = 1; VF = 0; CF = 0;'),
    ('COMB', 0o1051, 'local r = ~DstB; DstB = r; nzb(r); VF = 0; CF = 1;'),
    ('INCB', 0o1052, 'local d = DstB; VF = d == 0x7f; local r = d + 1; DstB = r; nzb(r);'),
    ('DECB', 0o1053, 'local d = DstB; VF = d == 0x80; local r = d - 1; DstB = r; nzb(r);'),
    ('NEGB', 0o1054, 'local d = DstB; local r = -d; DstB = r; nzb(r); VF = r == 0x80; CF = r != 0;'),
    ('ADCB', 0o1055, 'local d = DstB; local c:1 = CF; local r = d + c; VF = scarry(d, c); CF = carry(d, c); DstB = r; nzb(r);'),
    ('SBCB', 0o1056, 'local d = DstB; local c:1 = CF; local r = d - c; VF = sborrow(d, c); CF = d < c; DstB = r; nzb(r);'),
    ('TSTB', 0o1057, 'local d = DstB; nzb(d); VF = 0; CF = 0;'),
    ('RORB', 0o1060, 'local d = DstB; local c:1 = CF; local r = (d >> 1) | (c << 7); CF = (d & 1) != 0; DstB = r; nzb(r); VF = NF ^ CF;'),
    ('ROLB', 0o1061, 'local d = DstB; local c:1 = CF; local r = (d << 1) | c; CF = d s< 0; DstB = r; nzb(r); VF = NF ^ CF;'),
    ('ASRB', 0o1062, 'local d = DstB; local r = d s>> 1; CF = (d & 1) != 0; DstB = r; nzb(r); VF = NF ^ CF;'),
    ('ASLB', 0o1063, 'local d = DstB; local r = d << 1; CF = d s< 0; DstB = r; nzb(r); VF = NF ^ CF;'),
    ('MTPS', 0o1064, 'local v:1 = DstB; unpackpsw(v); packpsw();'),
]
for name, op, sem in SINGLEB:
    w(':%s DstB is op10=0x%03X ; DstB { %s }' % (name, op, sem))
w(':MFPS c_dreg is op10=0x237 & dmode=0 & c_dreg { packpsw(); local v:1 = PSW:1; c_dreg = sext(v); nzb(v); VF = 0; }')
w(':MFPS DstB is op10=0x237 ; DstB { packpsw(); local v:1 = PSW:1; DstB = v; nzb(v); VF = 0; }')

# ------------------------------------------------------------------ control flow
BR = [('BR', 0o0004, '1'), ('BNE', 0o0010, 'ZF == 0'), ('BEQ', 0o0014, 'ZF != 0'), ('BGE', 0o0020, 'NF == VF'),
      ('BLT', 0o0024, 'NF != VF'), ('BGT', 0o0030, 'ZF == 0 && NF == VF'), ('BLE', 0o0034, 'ZF != 0 || NF != VF'),
      ('BPL', 0o1000, 'NF == 0'), ('BMI', 0o1004, 'NF != 0'), ('BHI', 0o1010, 'CF == 0 && ZF == 0'),
      ('BLOS', 0o1014, 'CF != 0 || ZF != 0'), ('BVC', 0o1020, 'VF == 0'), ('BVS', 0o1024, 'VF != 0'),
      ('BCC', 0o1030, 'CF == 0'), ('BCS', 0o1034, 'CF != 0')]
for name, op, cond in BR:
    op8 = op >> 2
    if cond == '1':
        w(':%s Rel is op8=0x%02X & Rel { goto Rel; }' % (name, op8))
    else:
        w(':%s Rel is op8=0x%02X & Rel { if (%s) goto Rel; }' % (name, op8, cond))
w(':SOB sregx,SobT is op7=0x3F & sregx & SobT { sregx = sregx - 1; if (sregx != 0) goto SobT; }')
w(':JMP DstA is op10=0x001 ; DstA { goto [DstA]; }')
w(':JMP DstJ is op10=0x001 & dmode=6 & dregr=7 ; DstJ { goto DstJ; }')
w(':JMP DstJ is op10=0x001 & dmode=3 & dregr=7 ; DstJ { goto DstJ; }')
w(':JSR sregx,DstJ is op7=0x04 & sregr=7 & sregx & dmode=6 & dregr=7 ; DstJ { local ra:2 = inst_next; push(ra); call DstJ; }')
w(':JSR sregx,DstJ is op7=0x04 & sregr=7 & sregx & dmode=3 & dregr=7 ; DstJ { local ra:2 = inst_next; push(ra); call DstJ; }')
