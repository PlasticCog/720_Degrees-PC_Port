"""Generate t11_table.inc from MAME's T-11 opcode table and opcode implementations.

Each of the 8192 (opcode >> 3) slots gets {handler kind, cycles}, so the C++ T-11 core
reproduces MAME's cycle accounting exactly.
"""
import re, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
T11 = os.path.join(HERE, '..', 'Source_Emulator', 'mame', 'src', 'devices', 'cpu', 't11')
OUT = os.path.join(HERE, '..', 'port', 'src', 'ref', 't11_table.inc')

tab = open(os.path.join(T11, 't11table.hxx')).read()
names = re.findall(r'OP\((\w+)\)', tab.split('s_opcode_table')[1])
assert len(names) == 8192, len(names)

ops = open(os.path.join(T11, 't11ops.hxx')).read()
cyc = {}
for m in re.finditer(r'void t11_device::(\w+)\(uint16_t op\)\s*\{([^\n]*)\}', ops):
    name, body = m.group(1), m.group(2)
    c = re.search(r'm_icount -=\s*([0-9+ ]+);', body)
    if c:
        cyc[name] = eval(c.group(1))
# multi-line handlers
special = {'op_0000': 0, 'op_0001': 0, 'halt': 48, 'illegal': 48, 'illegal4': 48, 'mark': 36,
           'rts': 21, 'sob': 18, 'emt': 48, 'trap': 48}
for k, v in special.items():
    cyc.setdefault(k, v)

kinds = sorted(set(re.sub(r'_(rg|rgd|in|ind|de|ded|ix|ixd)(_(rg|rgd|in|ind|de|ded|ix|ixd))?$', '', n) for n in names))
missing = sorted(set(n for n in names if n not in cyc))
if missing:
    print('missing cycles for', missing)
    sys.exit(1)

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w') as f:
    f.write('// Generated by tools/gen_t11_table.py from MAME t11table.hxx / t11ops.hxx. Do not edit.\n')
    f.write('// Each entry: { handler kind, cycles }\n')
    f.write('enum T11Kind : uint8_t {\n')
    for k in kinds:
        f.write('\tK_%s,\n' % k.upper())
    f.write('};\n')
    f.write('static const struct { uint8_t kind; uint8_t cycles; } t11_table[8192] = {\n')
    for i, n in enumerate(names):
        k = re.sub(r'_(rg|rgd|in|ind|de|ded|ix|ixd)(_(rg|rgd|in|ind|de|ded|ix|ixd))?$', '', n)
        f.write('{K_%s,%d},' % (k.upper(), cyc[n]))
        if i % 8 == 7:
            f.write('\n')
    f.write('};\n')
print('kinds:', ' '.join(kinds))
print('wrote', OUT)
