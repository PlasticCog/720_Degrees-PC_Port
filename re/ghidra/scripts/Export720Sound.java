// Ghidra headless script: analyse the 720 Degrees sound program (6502) and export a
// labelled disassembly listing plus decompiled pseudo-C for every function.
// Usage (postScript): Export720Sound.java <coverage.txt> <output dir>
//@category 720Degrees
import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.*;
import ghidra.program.model.address.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.mem.*;
import ghidra.program.model.symbol.*;
import ghidra.app.cmd.disassemble.DisassembleCommand;
import java.io.*;
import java.util.*;

public class Export720Sound extends GhidraScript {
	private void label(long a, String name, String comment) throws Exception {
		Address ad = toAddr(a);
		currentProgram.getSymbolTable().createLabel(ad, name, SourceType.USER_DEFINED);
		if (comment != null) setPlateComment(ad, comment);
	}

	@Override
	public void run() throws Exception {
		String[] args = getScriptArgs();
		String covFile = args[0];
		String outDir = args[1];
		Memory mem = currentProgram.getMemory();
		int tx = currentProgram.startTransaction("720 setup");
		try {
			if (mem.getBlock(toAddr(0)) == null) {
				mem.createUninitializedBlock("RAM", toAddr(0x0000), 0x1000, false);
				mem.createUninitializedBlock("EEPROM", toAddr(0x1000), 0x200, false);
				mem.createUninitializedBlock("IO", toAddr(0x1800), 0x80, false);
			}
			String[] pokey = {"AUDF1", "AUDC1", "AUDF2", "AUDC2", "AUDF3", "AUDC3", "AUDF4", "AUDC4",
				"AUDCTL_ALLPOT", "STIMER_KBCODE", "SKREST_RANDOM", "POTGO", "unused", "SEROUT_SERIN", "IRQEN_IRQST", "SKCTL_SKSTAT"};
			for (int i = 0; i < 16; i++) {
				label(0x1800 + i, "POKEY1_" + pokey[i], null);
				label(0x1830 + i, "POKEY2_" + pokey[i], null);
			}
			label(0x1000, "EEPROM", "2804 parallel EEPROM, 512 bytes (high scores, settings)");
			label(0x1810, "LETA_CENTER", "720 controller: centre-disc counter");
			label(0x1811, "LETA_ROTATE", "720 controller: rotation counter (144 counts per turn)");
			label(0x1840, "IN1", "b0 cmd pending, b1 response pending, b2 TMS /READY, b4 self-test, b5 service, b6 coin L, b7 coin R (active low)");
			label(0x1850, "YM2151_ADDR", null);
			label(0x1851, "YM2151_DATA_STATUS", null);
			label(0x1860, "SOUND_CMD_READ", "command byte from the main CPU (clears pending)");
			label(0x1870, "TMS5220_DATA", null);
			label(0x1872, "TMS5220_WS_HIGH", null);
			label(0x1873, "TMS5220_WS_LOW", null);
			label(0x1874, "MAIN_RESPONSE_WRITE", "byte back to the main CPU");
			label(0x1876, "COIN_COUNTERS", null);
			label(0x1878, "IRQ_ACK", null);
			label(0x187A, "MIXER", "b0-2 YM2151 volume, b3-4 POKEY volume, b5-7 TMS5220 volume");
			label(0x187C, "CONTROL", "b2-3 LEDs, b5 TMS5220 clock select");
			label(0x187E, "SOUND_RESET", "b0: YM2151/TMS5220 reset");
			label(0x4000, "RESET", "6502 reset entry");
			label(0x57AC, "NMI_command_received", "NMI: main CPU wrote a sound command");
			label(0x4187, "IRQ_timer", "IRQ: 244 Hz periodic timer");

			// seed disassembly from runtime coverage
			AddressSet seeds = new AddressSet();
			BufferedReader br = new BufferedReader(new FileReader(covFile));
			String line;
			while ((line = br.readLine()) != null) {
				line = line.trim();
				if (line.isEmpty()) continue;
				long a = Long.parseLong(line, 16);
				if (a >= 0x4000) seeds.add(toAddr(a));
			}
			br.close();
			DisassembleCommand cmd = new DisassembleCommand(seeds, null, true);
			cmd.applyTo(currentProgram, monitor);
			for (long e : new long[] {0x4000, 0x57AC, 0x4187}) {
				disassemble(toAddr(e));
				createFunction(toAddr(e), null);
			}
		} finally {
			currentProgram.endTransaction(tx, true);
		}
		analyzeAll(currentProgram);

		// listing
		PrintWriter lst = new PrintWriter(new FileWriter(outDir + "/sound_6502.lst"));
		lst.println("; 720 Degrees sound program (6502), ROM 0x4000-0xFFFF");
		lst.println("; generated by re/ghidra/scripts/Export720Sound.java (Ghidra headless)");
		Listing listing = currentProgram.getListing();
		CodeUnitIterator it = listing.getCodeUnits(toAddr(0x4000), true);
		long lastData = -1;
		while (it.hasNext()) {
			CodeUnit cu = it.next();
			long a = cu.getAddress().getOffset();
			Symbol[] syms = currentProgram.getSymbolTable().getSymbols(cu.getAddress());
			if (cu instanceof Instruction) {
				String plate = cu.getComment(CodeUnit.PLATE_COMMENT);
				if (plate != null) lst.println("\n; " + plate.replace("\n", "\n; "));
				for (Symbol s : syms) lst.println(s.getName() + ":");
				StringBuilder bytes = new StringBuilder();
				for (byte b : cu.getBytes()) bytes.append(String.format("%02X ", b & 0xff));
				lst.println(String.format("  %04X  %-10s %s", a, bytes.toString(), cu.toString()));
			} else {
				Data d = (Data) cu;
				if (d.isDefined() || syms.length > 0) {
					for (Symbol s : syms) lst.println(s.getName() + ":");
					lst.println(String.format("  %04X  %s", a, cu.toString()));
				}
			}
		}
		lst.close();

		// decompiled pseudo-C
		DecompInterface ifc = new DecompInterface();
		ifc.openProgram(currentProgram);
		PrintWriter c = new PrintWriter(new FileWriter(outDir + "/sound_6502_decompiled.c"));
		c.println("/* 720 Degrees sound program - Ghidra decompiler output (pseudo-C, for reference only) */");
		int nf = 0;
		for (Function f : currentProgram.getFunctionManager().getFunctions(true)) {
			DecompileResults res = ifc.decompileFunction(f, 60, monitor);
			if (res != null && res.decompileCompleted()) {
				c.println(res.getDecompiledFunction().getC());
				nf++;
			}
		}
		c.close();
		println("exported " + nf + " functions");
	}
}
